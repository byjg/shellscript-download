// Generates a bash completion script for load.sh from the print_usage() flags of each script
// Runs automatically in npm prebuild
import { promises as fs } from 'fs'
import path from 'path'
import url from 'url'

const __dirname = path.dirname(url.fileURLToPath(import.meta.url))

function extractPrintUsage(content) {
  const lines = content.split(/\r?\n/)
  const result = []
  let inUsageFunction = false
  let inHeredoc = false

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    if (line.match(/^\s*print_usage\(\)\s*\{/)) { inUsageFunction = true; continue }
    if (inUsageFunction) {
      if (line.match(/cat\s*<<'?USAGE'?/)) { inHeredoc = true; continue }
      if (inHeredoc && line.trim() === 'USAGE') break
      if (inHeredoc) result.push(line)
    }
  }
  return result.join('\n')
}

function extractFlags(usageText) {
  const flags = new Set()
  for (const line of usageText.split(/\r?\n/)) {
    if (!/^\s+-/.test(line)) continue
    for (const m of line.matchAll(/(?<!\w)(--?[\w-]+)/g)) flags.add(m[1])
  }
  return [...flags].sort()
}

async function generate() {
  const repoRoot = path.resolve(__dirname, '..')
  const publicScriptsDir = path.join(repoRoot, 'public', 'scripts')

  const entries = (await fs.readdir(publicScriptsDir, { withFileTypes: true }))
    .filter(e => e.isFile() && ['.sh', '.bash', '.zsh'].includes(path.extname(e.name).toLowerCase()))

  const scripts = []
  for (const entry of entries) {
    const base = path.basename(entry.name, path.extname(entry.name))
    if (['load', 'remove'].includes(base)) continue
    const content = await fs.readFile(path.join(publicScriptsDir, entry.name), 'utf8')
    const flags = extractFlags(extractPrintUsage(content))
    scripts.push({ base, flags })
  }

  scripts.sort((a, b) => a.base.localeCompare(b.base))

  const loadContent = await fs.readFile(path.join(publicScriptsDir, 'load.sh'), 'utf8')
  const loadFlags = extractFlags(extractPrintUsage(loadContent))

  const topLevelWords = [...loadFlags, ...scripts.map(s => s.base)].join(' ')
  const cases = scripts
    .map(({ base, flags }) => `    ${base}) mapfile -t COMPREPLY < <(compgen -W "${flags.join(' ')}" -- "$cur") ;;`)
    .join('\n')

  const completion = `#!/usr/bin/env bash
# load-completion.sh: Bash completion for load.sh
# Auto-generated by scripts/generate-completion.mjs — do not edit.
# Usage: source this file, or place it in /etc/bash_completion.d/

_load_sh_completion() {
  local cur
  cur="\${COMP_WORDS[COMP_CWORD]}"

  if [[ \$COMP_CWORD -eq 1 ]]; then
    mapfile -t COMPREPLY < <(compgen -W "${topLevelWords}" -- "$cur")
    return
  fi

  case "\${COMP_WORDS[1]}" in
${cases}
    *) COMPREPLY=() ;;
  esac
}

complete -F _load_sh_completion load.sh
`

  await fs.writeFile(path.join(repoRoot, 'public', 'install', 'load-completion.sh'), completion, 'utf8')
  return scripts.length
}

if (import.meta.url === url.pathToFileURL(process.argv[1]).href) {
  generate()
    .then(n => console.log(`[generate-completion] Generated bash completion for ${n} script(s) → public/install/load-completion.sh`))
    .catch(err => { console.error('[generate-completion] Failed:', err); process.exit(1) })
}