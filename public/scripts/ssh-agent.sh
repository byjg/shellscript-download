#!/usr/bin/env bash
# ssh-agent.sh: Configure ssh-agent startup and SSH key loading in your shell

set -euo pipefail

print_usage() {
  cat <<'USAGE'
load.sh ssh-agent -- [options]

Writes a shell init snippet that, on every new shell session, finds an
ssh-agent and loads the SSH keys that are not in it yet.

All shells share one agent: the one of the session when it answers, then the
one of systemd ($XDG_RUNTIME_DIR/openssh_agent), then one started on
~/.ssh/agent.sock. A key that is missing or cannot be added is warned about.

By default, all private keys found in ~/.ssh are added. Use --key to add
only specific keys; a key that does not exist is an error. Running this script
again overwrites the previous config.

Options:
  -h, --help       Show this help and exit
  --dry-run        Print actions without executing them
  --manifest       Print installation manifest and exit
  --key <path>     Add this key (can be repeated for multiple keys)

Examples:
  load.sh ssh-agent
  load.sh ssh-agent -- --key ~/.ssh/id_ed25519
  load.sh ssh-agent -- --key ~/.ssh/id_rsa --key ~/.ssh/work_key
  load.sh ssh-agent -- --dry-run
USAGE
}

print_manifest() {
  cat <<'MANIFEST'
BIN_FILES=
FOLDERS=
SHELLRC_FILE=$HOME/.shellscript/shellrc/ssh-agent-init.sh
MANIFEST
}

# Parse flags
DRY_RUN=0
KEYS=()

while [[ ${1-} ]]; do
  case "$1" in
    -h|--help)   print_usage; exit 0 ;;
    --manifest)  print_manifest; exit 0 ;;
    --dry-run)   DRY_RUN=1 ;;
    --key)
      shift || { err "--key requires a value"; exit 2; }
      KEYS+=("$1")
      ;;
    *) err "Unknown option: $1"; print_usage; exit 2 ;;
  esac
  shift || true
done

require_cmd ssh-agent
require_cmd ssh-add

# If no keys specified, discover all private keys in ~/.ssh
if [[ ${#KEYS[@]} -eq 0 ]]; then
  while IFS= read -r -d '' f; do
    # Skip public keys, known_hosts, config, and authorized_keys
    [[ "$f" == *.pub ]]             && continue
    [[ "$f" == */known_hosts ]]     && continue
    [[ "$f" == */known_hosts.old ]] && continue
    [[ "$f" == */config ]]          && continue
    [[ "$f" == */authorized_keys ]] && continue
    KEYS+=("$f")
  done < <(find "${HOME}/.ssh" -maxdepth 1 -type f -print0 2>/dev/null)
fi

if [[ ${#KEYS[@]} -eq 0 ]]; then
  err "No SSH private keys found in ~/.ssh. Use --key <path> to specify one."
  exit 1
fi

for k in "${KEYS[@]}"; do
  [[ -r "$k" ]] || { err "Key not found: $k"; exit 1; }
done

log "Configuring ssh-agent with ${#KEYS[@]} key(s):"
for k in "${KEYS[@]}"; do
  log "  $k"
done

run "mkdir -p \"${SHELLSCRIPT_SHELLRC}\""

if [[ "$DRY_RUN" == "1" ]]; then
  log "[dry-run] Writing ${SHELLSCRIPT_SHELLRC}/ssh-agent-init.sh"
  log "[dry-run] Keys to be added:"
  for k in "${KEYS[@]}"; do
    log "[dry-run]   ssh-add \"${k}\""
  done
else
  run "mkdir -p \"${HOME}/.ssh\" && chmod 700 \"${HOME}/.ssh\""
  # Build the init file — overwrite any previous version
  {
    cat <<'INIT'
# ssh-agent-init.sh — generated by ssh-agent.sh (do not edit manually)
# ssh-add -l: 0 has keys, 1 has none, 2 no agent answers
__ssh_agent_up() { ssh-add -l >/dev/null 2>&1; [ $? -ne 2 ]; }

# One agent for all shells: the one of the session, of systemd, or ours
if [ -z "${SSH_AUTH_SOCK-}" ] || ! __ssh_agent_up; then
  SSH_AUTH_SOCK="${XDG_RUNTIME_DIR-}/openssh_agent"; export SSH_AUTH_SOCK
  if ! __ssh_agent_up; then
INIT
    printf '    SSH_AUTH_SOCK="%s"\n' "${HOME}/.ssh/agent.sock"
    cat <<'INIT'
    if ! __ssh_agent_up; then
      rm -f "$SSH_AUTH_SOCK"
      eval "$(ssh-agent -s -a "$SSH_AUTH_SOCK")" >/dev/null
    fi
  fi
fi

# __ssh_agent_needs <key>: true when the key is there and not in the agent yet
__ssh_agent_needs() {
  if [ ! -r "$1" ]; then
    echo "ssh-agent-init: key not found: $1" >&2
    return 1
  fi
  __ssh_agent_fp="$(ssh-keygen -lf "$1" 2>/dev/null | cut -d' ' -f2)"
  [ -z "$__ssh_agent_fp" ] || ! ssh-add -l 2>/dev/null | grep -qF "$__ssh_agent_fp"
}

# Load SSH keys
INIT
    for k in "${KEYS[@]}"; do
      printf '__ssh_agent_needs "%s" && ssh-add "%s"\n' "$k" "$k"
    done
    printf '\nunset -f __ssh_agent_up __ssh_agent_needs\nunset __ssh_agent_fp\n'
  } > "${SHELLSCRIPT_SHELLRC}/ssh-agent-init.sh"

  log "Done. Shell init written to ${SHELLSCRIPT_SHELLRC}/ssh-agent-init.sh"
  log "It will be sourced automatically on every new shell session via load.sh."
fi
